PalConsoleCommands::Catalog() noexcept {
    return kCommands;
}

std::uint32_t PalConsoleCommands::Initialize(
    PalConsoleAccessState& access_state,
    IPalConsoleAccessRuntime& access_runtime,
    IPalConsoleObjectRuntime& object_runtime,
    std::int32_t width, std::int32_t height) {
    const auto console = PalConsoleAccess::Get(access_state, access_runtime);
    (void)PalConsole::InitializeRectangles(
        object_runtime.Access(console), width, height);
    std::uint32_t result = 0u;
    for (const auto& command : kCommands) {
        const auto current = PalConsoleAccess::Get(access_state, access_runtime);
        result = PalConsole::AddCommand(current, command.callback,
                                        command.name, command.description,
                                        object_runtime) ? 1u : 0u;
    }
    return result;
}


struct Runtime final : RuntimeInterface {
    explicit Runtime(const Spec& expected_spec) : expected(expected_spec) {}

    const Spec& expected;
    std::vector<std::string> calls;
    int result = -7;

    void RegisterBuiltin(const pal4::StaticBuiltin builtin,
                         const std::uint32_t descriptor) override {
        Check(builtin == expected.builtin &&
                  descriptor == expected.descriptor,
              "script built-in target and static descriptor");
        calls.emplace_back("register");
    }
    int RegisterAtExit(const std::uint32_t callback) override {
        Check(callback == expected.cleanup, "matching cleanup callback");
        calls.emplace_back("atexit");
        return result;
    }
    void DeallocateDescriptor(const std::uint32_t descriptor) override {
        Check(descriptor == expected.descriptor,
              "matching descriptor deallocation");
        calls.emplace_back("deallocate");
    }
};

void TestAllStaticRegistrations() {
    for (const auto& spec : kSpecs) {
        Runtime runtime(spec);
        Check(spec.initialize(runtime) == -7 &&
                  runtime.calls ==
                      std::vector<std::string>{"register", "atexit"},
              "initializer registers descriptor before atexit");
        spec.cleanup_descriptor(runtime);
        Check(runtime.calls.back() == "deallocate",
              "atexit wrapper frees its descriptor");

        Runtime direct(spec);
        spec.register_descriptor(direct);
        spec.cleanup_descriptor(direct);
        Check(direct.calls ==
                  std::vector<std::string>{"register", "deallocate"},
              "direct wrapper entrypoints forward independently");
    }
}

void TestActorManagerScriptBuiltins() {
    using Registration = pal4::ActorManagerScriptBuiltinRegistration;
    struct Expected {
        pal4::StaticBuiltin builtin;
        std::uint32_t descriptor;
        std::uint32_t native_entry;
        std::uint32_t initializer;
        std::uint32_t wrapper;
        std::uint32_t cleanup;
    };
    constexpr std::array<Expected,
                         static_cast<std::size_t>(pal4::StaticBuiltin::Count)>
        expected{{
#include "data/actor_manager_script_builtin_expected.inc"
    }};
    struct ActorManagerRuntime final : RuntimeInterface {
        explicit ActorManagerRuntime(const Expected& item) : expected(item) {}
        const Expected& expected;
        std::vector<std::string> calls;
        int result = -23;
        bool fail_registration = false;
        bool fail_atexit = false;

        void RegisterBuiltin(pal4::StaticBuiltin,
                             std::uint32_t) override {
            Check(false, "actor-manager registration must forward native entry");
        }
        void RegisterBuiltinAt(const pal4::StaticBuiltin builtin,
                               const std::uint32_t descriptor,
                               const std::uint32_t native_entry) override {
            Check(builtin == expected.builtin &&
                      descriptor == expected.descriptor &&
                      native_entry == expected.native_entry,
                  "actor-manager descriptor and native registration target");
            calls.emplace_back("register");
            if (fail_registration) throw std::runtime_error("registration");
        }
        int RegisterAtExit(const std::uint32_t callback) override {
            Check(callback == expected.cleanup,
                  "actor-manager matching cleanup callback");
            calls.emplace_back("atexit");
            if (fail_atexit) throw std::runtime_error("atexit");
            return result;
        }
        void DeallocateDescriptor(const std::uint32_t descriptor) override {
            Check(descriptor == expected.descriptor,
                  "actor-manager matching descriptor deallocation");
            calls.emplace_back("deallocate");
        }
    };
    for (const auto& item : expected) {
        const auto spec = Registration::SpecFor(item.builtin);
        Check(spec.descriptor == item.descriptor &&
                  spec.native_entry == item.native_entry &&
                  spec.initializer == item.initializer &&
                  spec.wrapper == item.wrapper &&
                  spec.cleanup == item.cleanup,
              "actor-manager IDA address mapping");
        ActorManagerRuntime initialized(item);
        Check(Registration::Initialize(item.builtin, initialized) == -23 &&
                  initialized.calls ==
                      std::vector<std::string>{"register", "atexit"},
              "actor-manager registration precedes atexit and returns result");
        ActorManagerRuntime direct(item);
        Registration::Register(item.builtin, direct);
        Registration::Cleanup(item.builtin, direct);
        Check(direct.calls ==
                  std::vector<std::string>{"register", "deallocate"},
              "actor-manager wrappers forward independently");
    }
    bool caught = false;
    try { (void)Registration::SpecFor(pal4::StaticBuiltin::Count); }
    catch (const std::out_of_range&) { caught = true; }
    Check(caught, "actor-manager invalid built-in index is rejected");

    ActorManagerRuntime failed(expected.front());
    failed.fail_registration = true;
    caught = false;
    try { (void)Registration::Initialize(expected.front().builtin, failed); }
    catch (const std::runtime_error&) { caught = true; }
    Check(caught && failed.calls == std::vector<std::string>{"register"},
          "failed registration skips atexit");
    failed.calls.clear();
    failed.fail_registration = false;
    failed.fail_atexit = true;
    caught = false;
    try { (void)Registration::Initialize(expected.front().builtin, failed); }
    catch (const std::runtime_error&) { caught = true; }
    Check(caught && failed.calls ==
              std::vector<std::string>{"register", "atexit"},
          "atexit failure occurs after registration");
}

